/**
 * Changelog generator — turns `git log` into lib/changelog.js at build time.
 *
 * Run from anywhere inside the repo BEFORE building the docs app:
 *   node apps/docs/lib/gen-changelog.js
 *
 * Commit convention parsed: "area: description" (e.g. "docs: add zhost guide").
 * Merge commits, wip, and chore-noise are skipped. The generated module ships
 * with the release, so production never needs .git.
 */

import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SEP = "\u001f"; // unit separator — never appears in commit messages

const raw = execSync(
  `git log --no-merges --date=short --pretty=format:%H${SEP}%ad${SEP}%s -n 200`,
  { cwd: here, encoding: "utf8" },
);

const SKIP = /^(wip|tmp|fixup|squash)\b|^Merge\b/i;

const entries = [];
for (const line of raw.split("\n")) {
  const [hash, date, subject] = line.split(SEP);
  if (!hash || !subject || SKIP.test(subject)) continue;
  const m = subject.match(/^([\w+/-]+):\s*(.+)$/);
  const area = m ? m[1].toLowerCase() : "core";
  const text = m ? m[2] : subject;
  entries.push({ hash: hash.slice(0, 7), date, area, text });
}

const out =
  "/** AUTO-GENERATED by lib/gen-changelog.js — do not edit. */\n" +
  `export const GENERATED_AT = ${JSON.stringify(new Date().toISOString().slice(0, 10))};\n` +
  `export const ENTRIES = ${JSON.stringify(entries, null, 1)};\n`;

writeFileSync(join(here, "changelog.js"), out);
console.log(`changelog.js written — ${entries.length} entries (latest: ${entries[0]?.date ?? "none"})`);
